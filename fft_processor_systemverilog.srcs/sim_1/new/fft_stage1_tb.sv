`timescale 1ns/1ps

import fft_pkg::*;

module fft_stage1_tb;

    //--------------------------------------------------
    // Inputs and Outputs
    //--------------------------------------------------

    complex_t x [0:7];
    complex_t y [0:7];

    //--------------------------------------------------
    // Device Under Test
    //--------------------------------------------------

    fft_stage1 DUT (
        .x(x),
        .y(y)
    );

    //--------------------------------------------------
    // Test
    //--------------------------------------------------

    initial begin

        //--------------------------------------------------
        // Bit-reversed input for DIT FFT
        //
        // Original sequence:
        // 1 2 3 4 5 6 7 8
        //
        // Bit-reversed order:
        // 1 5 3 7 2 6 4 8
        //--------------------------------------------------

        x[0].real_part = 1;
        x[1].real_part = 5;
        x[2].real_part = 3;
        x[3].real_part = 7;
        x[4].real_part = 2;
        x[5].real_part = 6;
        x[6].real_part = 4;
        x[7].real_part = 8;

        //--------------------------------------------------
        // Imaginary inputs
        //--------------------------------------------------

        for (int i = 0; i < 8; i++) begin
            x[i].imag_part = 0;
        end

        //--------------------------------------------------
        // Allow combinational logic to settle
        //--------------------------------------------------

        #20;

        //--------------------------------------------------
        // Display output
        //--------------------------------------------------

        $display("-----------------------------------------------");
        $display("           FFT Stage 1 Output");
        $display("-----------------------------------------------");

        for (int i = 0; i < 8; i++) begin

            $display("y[%0d] = %0d + j%0d",
                     i,
                     y[i].real_part,
                     y[i].imag_part);

        end

        $display("-----------------------------------------------");

        $finish;

    end

endmodule